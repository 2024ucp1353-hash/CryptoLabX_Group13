
import random
import time

TOKEN_LENGTH = 16
TIME_WINDOW = 300


def generate_token_from_timestamp(timestamp):
    rng = random.Random(timestamp)
    token = bytes(rng.getrandbits(8) for _ in range(TOKEN_LENGTH))
    return token


def predict_timestamp_seed(observed_token, center_timestamp):
    start_time = center_timestamp - TIME_WINDOW
    end_time = center_timestamp + TIME_WINDOW

    timestamps_tested = 0

    for timestamp in range(start_time, end_time + 1):
        candidate_token = generate_token_from_timestamp(timestamp)
        timestamps_tested += 1

        if candidate_token == observed_token:
            return timestamp, timestamps_tested

    return None, timestamps_tested


